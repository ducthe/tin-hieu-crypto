"""Gộp engine.js + market.js + update-signals/index.ts thành MỘT file để dán vào
trình soạn thảo Edge Function trên Supabase Dashboard (không cần cài Node/CLI).

Chạy:  python tools/bundle_edge_function.py
Kết quả: dist/update-signals.ts
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FN = ROOT / "supabase" / "functions"
OUT = ROOT / "dist" / "update-signals.ts"

LOCAL_IMPORT = re.compile(r"^import .* from '\.{1,2}/.*';\s*$", re.M)


def strip(src: str) -> str:
    src = LOCAL_IMPORT.sub("", src)
    return re.sub(r"^export (const|function|async function) ", r"\1 ", src, flags=re.M)


parts = [
    "// @ts-nocheck",
    "// AUTO-GENERATED by tools/bundle_edge_function.py — do not edit; edit the source files instead.",
    "",
    "// ===== _shared/engine.js =====",
    strip((FN / "_shared" / "engine.js").read_text(encoding="utf-8")),
    "// ===== _shared/market.js =====",
    strip((FN / "_shared" / "market.js").read_text(encoding="utf-8")),
    "// ===== update-signals/index.ts =====",
    strip((FN / "update-signals" / "index.ts").read_text(encoding="utf-8")),
]
OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(parts), encoding="utf-8")
print(f"OK -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
